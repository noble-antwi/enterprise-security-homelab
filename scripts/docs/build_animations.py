"""Build the animated diagrams from their static twins (SMIL animation, plays on GitHub).

Edit the static SVG in images/diagrams/, then re-run:
    python scripts/docs/build_animations.py

The static SVG stays the source of truth and is what the PDF build embeds; the
animated copy is what the chapter shows on GitHub.
"""
from pathlib import Path

DIAGRAMS = Path(__file__).resolve().parents[2] / "images" / "diagrams"

CYAN, GREEN, RED, GLOW = "#0E7490", "#0F6E56", "#B0422A", "#2DD4E8"


def f(x):
    return f"{x:.3f}".rstrip("0").rstrip(".") if x else "0"


def window(a, b, D, eps=0.012):
    """Opacity animate: visible between fractions a and b of the loop."""
    kt = ";".join(f(t) for t in (0, a - eps, a, b, b + eps, 1))
    return (f'<animate attributeName="opacity" dur="{D}s" repeatCount="indefinite" '
            f'values="0;0;1;1;0;0" keyTimes="{kt}"/>')


def frame(x, y, w, h, a, b, D, color=GLOW, rx=10):
    """A glowing outline around a box while its step is active."""
    return (f'\n  <rect x="{x - 4}" y="{y - 4}" width="{w + 8}" height="{h + 8}" rx="{rx}" fill="none" '
            f'stroke="{color}" stroke-width="3" opacity="0">{window(a, b, D)}</rect>')


def dot(path, s, e, color, D):
    """A pulsing dot that travels along a path between fractions s and e."""
    return f'''
  <g opacity="0">
    <animateMotion path="{path}" dur="{D}s" repeatCount="indefinite" calcMode="linear" keyPoints="0;0;1;1" keyTimes="0;{f(s)};{f(e)};1"/>
    {window(s, e, D)}
    <circle r="11" fill="{color}" opacity="0.3"><animate attributeName="r" values="8;15;8" dur="0.9s" repeatCount="indefinite"/></circle>
    <circle r="6" fill="{color}" stroke="#FFFFFF" stroke-width="2"/>
  </g>'''


def ring(cx, cy, r0, r1, color, a, b, D):
    """An expanding ring: something is being checked here."""
    return f'''
  <g opacity="0">{window(a, b, D)}
    <circle cx="{cx}" cy="{cy}" r="{r0}" fill="none" stroke="{color}" stroke-width="2.5">
      <animate attributeName="r" values="{r0};{r1}" dur="0.9s" repeatCount="indefinite"/>
      <animate attributeName="stroke-opacity" values="0.9;0" dur="0.9s" repeatCount="indefinite"/>
    </circle>
  </g>'''


def progress(D, y, width):
    return (f'\n  <rect x="0" y="{y}" width="0" height="3" fill="{GLOW}">'
            f'<animate attributeName="width" values="0;{width}" dur="{D}s" repeatCount="indefinite"/></rect>')


# ------------------------------------------------- how IDP01 gets its certificate
D = 16
svg = (DIAGRAMS / "idp01-cert-flow.svg").read_text(encoding="utf-8")

layer = "\n  <!-- Motion layer (generated by scripts/docs/build_animations.py) -->"
layer += progress(D, 63, 680)
# 1. IDP01 makes the key pair and the request; the key never moves.
layer += frame(38, 124, 182, 74, 0.02, 0.18, D)
layer += frame(38, 314, 182, 48, 0.02, 0.18, D, color=GREEN)
# 2. The request (public key + name) travels to CA01.
layer += frame(262, 128, 156, 22, 0.18, 0.36, D, rx=13)
layer += dot("M236 161 H444", 0.19, 0.35, CYAN, D)
# 3. CA01 first refuses the local account, then checks the domain requester and signs.
layer += frame(460, 314, 182, 48, 0.36, 0.45, D, color=RED)
layer += ring(551, 338, 14, 46, RED, 0.36, 0.45, D)
layer += frame(460, 124, 182, 166, 0.45, 0.60, D)
layer += ring(551, 234, 14, 60, GREEN, 0.50, 0.60, D)
# 4. The signed certificate travels back.
layer += frame(262, 229, 156, 22, 0.60, 0.78, D, rx=13)
layer += dot("M444 262 H238", 0.61, 0.77, GREEN, D)
# 5. IDP01 checks the signature against the Biira root: OK.
layer += frame(38, 222, 182, 80, 0.78, 0.97, D)
layer += ring(158, 282, 10, 40, GREEN, 0.86, 0.97, D)
layer += frame(38, 314, 182, 48, 0.86, 0.97, D, color=GREEN)

svg = svg.replace("</svg>", layer + "\n</svg>")
(DIAGRAMS / "idp01-cert-flow-animated.svg").write_text(svg, encoding="utf-8")
print("idp01-cert-flow-animated.svg")
